package main

import "fmt"

//old struct
type OldCalculator struct{}

func (oc *OldCalculator) Compute(value int) int {
	return value * 2
}

//new interface
type Server interface {
	Calculate(i int) bool
}

//adapter (old struct -> new interface)
type ServerAdapter struct {
	oldCalculator *OldCalculator
}

func NewServerAdapter(oldCalc *OldCalculator) *ServerAdapter {
	return &ServerAdapter{oldCalculator: oldCalc}
}

func (sa *ServerAdapter) Calculate(i int) bool {
	result := sa.oldCalculator.Compute(i)
	return result >= 10
}

//client
func process(server Server) {
	for i := 1; i <= 5; i++ {
		result := server.Calculate(i)
		fmt.Println(result)
	}
}

func main() {
	oldCalc := &OldCalculator{}
	adapter := NewServerAdapter(oldCalc)
	process(adapter)
}

// Применимость: когда нужно использовать старый код в новой системе(интеграция легаси кода);
// 			  при работе с сторонними библиотеками API которых не соответствует нашим интерфейсам;
// 			  при унификации интерфейсов если несколько разных классов должны работать одинаково, либо при необходимости заменять компоненты системы по частям;
// 			  нужно чтобы клиент зависел от интерфейса а не конкретной реализации;
// Плюсы: соблюдение принципов solid
// 			Open/Closed -система открыта для расширения адаптерами но закрыта для модификации сущ. кода;
// 	   		DI - клиенты зависят от абстракций а не от реализаций;
// 			Single Responsibility - адаптер отвечает тоолько за преобразование интерфейсов;
// 		повторное использование существующего кода: легаси система продолжает работать, не нужно переписывать проверенный код, экономия времени и снижение рисков
// 		гибкость и расширяемость, упрощение тестирования(лего создавать мок адаптеры для тестов)
// Минусы: усложнение архитектуры и читаемости кода - добавляется слой абстракции
// 		оверхед производительности - доп. вызовы методов, аллокации, преобразования;
// 		адаптерный адаптер - антипаттерн, слишком много уровней абстракции, сложно отлаживать, потеря производительности
// 		дублирование кода при множественных адаптациях - если нужно адаптировать один класс к разным интерфейсам;
// 		адаптер может добавиться как временное решение, но остаться в коде навсегда, сложнее позже провести полный рефакторинг;
// 		невозможно добавить новые методы к старому коду через адаптер;
// Примеры использования:
// 	1) Есть старый банковский софт, который работает через SOAP/XML. Нужно подключить его к новому мобильному приложению, которое использует REST/JSON.
